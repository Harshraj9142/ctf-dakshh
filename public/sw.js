const CACHE_NAME = "dakshh-cyber-rooms-v1";

// ========================================
// 🏴 FLAG: dakshh{service_worker_shadow}
// ========================================

self.addEventListener("install", (event) => {
    self.skipWaiting();
});

self.addEventListener("activate", (event) => {
    event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", (event) => {
    const url = new URL(event.request.url);

    // Intercept /api/secret requests
    if (url.pathname === "/api/secret") {
        event.respondWith(
            new Response(
                JSON.stringify({
                    status: "intercepted",
                    message: "This response was generated by the service worker, not the server.",
                    hint: "The flag is in the service worker source code. Visit /sw.js directly.",
                    shadow_data: {
                        proxy_version: "1.0.0",
                        intercept_count: Math.floor(Math.random() * 100),
                        // The flag is intentionally NOT here — it's in the comments above
                        // This teaches that service workers can fully control responses
                        real_endpoint: "/api/secret (intercepted)",
                    },
                }),
                {
                    status: 200,
                    headers: {
                        "Content-Type": "application/json",
                        "X-Intercepted-By": "shadow-proxy",
                        "X-Hint": "Read /sw.js source code for the flag",
                    },
                }
            )
        );
        return;
    }
});
